#!/usr/bin/env node
// Generates src/backends/ort-pins.ts from node_modules/onnxruntime-web/dist: the version and the
// sha256 of the ONNX Runtime Web wasm binary and wasm factory (.mjs) the engine adapters accept.
// A runtimeWasm entry whose sha256 differs from the pin for its device is refused (bad_descriptor),
// so a signed manifest cannot smuggle in a different engine binary. test/ort-pins.test.ts re-hashes
// the installed files and fails on drift.
//
//   node test/tools/gen-ort-pins.mjs [--wasm-file <name>] [--factory-file <name>]
//                                    [--webgpu-wasm-file <name>] [--webgpu-factory-file <name>] [--check]
//
// The default is the asyncify variant, which @huggingface/transformers selects for both devices;
// the files actually loaded per device are confirmed from the network log in the model test
// (test/browser/model.spec.ts records them in model-run.json); regenerate with the per-device flags
// if the two paths ever load different variants.

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const dist = resolve(root, 'node_modules/onnxruntime-web/dist');
const out = resolve(root, 'src/backends/ort-pins.ts');

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : fallback;
}
const sha = (file) => {
  const p = resolve(dist, file);
  if (!existsSync(p)) throw new Error(`${p} is not installed`);
  return createHash('sha256').update(readFileSync(p)).digest('hex');
};
const check = (file, re) => {
  if (!re.test(file) || file.includes('/')) throw new Error(`refusing ORT file name ${file}`);
  return file;
};

const version = JSON.parse(
  readFileSync(resolve(root, 'node_modules/onnxruntime-web/package.json'), 'utf8'),
).version;
const wasmFile = check(
  arg('--wasm-file', 'ort-wasm-simd-threaded.asyncify.wasm'),
  /^ort-wasm-[a-z.-]+\.wasm$/,
);
const factoryFile = check(
  arg('--factory-file', 'ort-wasm-simd-threaded.asyncify.mjs'),
  /^ort-wasm-[a-z.-]+\.mjs$/,
);
const gpuWasm = check(arg('--webgpu-wasm-file', wasmFile), /^ort-wasm-[a-z.-]+\.wasm$/);
const gpuFactory = check(arg('--webgpu-factory-file', factoryFile), /^ort-wasm-[a-z.-]+\.mjs$/);

const pin = (w, f) =>
  `{ wasmFile: '${w}', wasmSha256: '${sha(w)}', factoryFile: '${f}', factorySha256: '${sha(f)}' }`;

const text = `// Generated by test/tools/gen-ort-pins.mjs from node_modules/onnxruntime-web/dist. Do not edit.
// A runtimeWasm entry whose sha256 differs from the pin for its device is refused (bad_descriptor).
// test/ort-pins.test.ts re-hashes the installed files and fails on drift.

export const ORT_WEB_VERSION = '${version}';
export const ORT_WASM_FILE = '${wasmFile}';
export const ORT_WASM_SHA256 = '${sha(wasmFile)}';
export const ORT_FACTORY_FILE = '${factoryFile}';
export const ORT_FACTORY_SHA256 = '${sha(factoryFile)}';

/** One pin per execution device (identical while both paths load the same wasm variant). */
export const ORT_PINS = {
  wasm: ${pin(wasmFile, factoryFile)},
  webgpu: ${pin(gpuWasm, gpuFactory)},
} as const;
`;
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  // compare modulo Prettier formatting by normalising whitespace
  const norm = (s) =>
    s
      .replace(/\s+/g, ' ')
      .replace(/,\s*\}/g, ' }')
      .trim();
  if (norm(current) !== norm(text)) {
    console.error('src/backends/ort-pins.ts is out of date: run node test/tools/gen-ort-pins.mjs');
    process.exit(1);
  }
  console.log('ort-pins.ts is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
