import { defineConfig } from 'tsup';

// The release tool (spec 0.6.1, manifest 0.1.4 "Release manifests"): runtime's own verifier, bundled into one file
// that imports only node:crypto, node:fs, node:fs/promises, node:path, node:process and node:url. Everything else
// (verifyManifest, canonical(), the strict JSON scan, the weak-key code, the schemas) is bundled from src/ and spec/,
// so a verdict of the tool can never differ from the library's. Built by `npm run spec:release-tool`; the output is
// committed with its .sha256 and a test rebuilds it and compares the bytes. Not minified, no source map.
export default defineConfig({
  entry: { 'release-tool': 'src/release/bin.ts' },
  format: ['esm'],
  platform: 'node',
  target: 'node22',
  outDir: 'spec/tools',
  outExtension: () => ({ js: '.mjs' }),
  clean: false,
  dts: false,
  sourcemap: false,
  minify: false,
  splitting: false,
  treeshake: true,
  noExternal: [/.*/],
  // keep `node:` on every import: the allowlist test and a reader both look for the protocol
  removeNodeProtocol: false,
  banner: {
    js: '// @airplanemode/runtime release tool, spec release 0.6.1 (manifest 0.1.4, Release manifests). Generated by `npm run spec:release-tool` from src/release/; do not edit. Apache-2.0.',
  },
  esbuildOptions(options) {
    options.legalComments = 'none';
  },
});
